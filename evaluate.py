OLLAMA_BASE_URL = "http://localhost:11434"
CHROMA_DIR = "./chroma_langchain_db"
EXPECTED_ANSWERS_PATH = "./expected_answers.csv"
RESULTS_PATH = "./experiment_results.csv"
