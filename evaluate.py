"""
evaluate.py

RAG evaluation pipeline for the UiA IKT course chatbot.

Generator : phi4:14b     (Ollama, GPU) — strong instruction following
Judge     : qwen2.5:7b   (Ollama, GPU) — reliable structured JSON output

Expected answers are loaded from expected_answers.csv (generated by
generate_expected_answers.py).  The relevance judge compares the RAG
answer against the reference answer, making scoring much more reliable
than judging against the question alone.

Requires:
    Ollama running with phi4:14b and qwen2.5:7b pulled (uses GPU automatically)
"""

